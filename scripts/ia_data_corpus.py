#!/usr/bin/env python3
"""IA-DATA-01 L1: synthetic corpus of candidate stitch plans, measured by the engine.

Python standard library only. Pipeline:

  generate : seeded synthetic shapes (mm, Y up) -> shapes.jsonl
  build    : shapes + openstitch-cli -> candidates.jsonl + manifest.json
  validate : schema and SHA-256 checks of a built corpus

Every metric comes from `openstitch-cli project check/density --json` on the
effective sequence; nothing is estimated here. No label is produced: choosing a
"best" candidate needs a documented proxy policy or human review (L3), and the
engine's own defaults are not ground truth. No network, no third-party asset.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import math
import os
from pathlib import Path
import random
import subprocess
import sys
import tempfile

GENERATOR = "ia_data_corpus/1"
SHAPE_SCHEMA = "openstitch.ia-data.shape/1"
SET_SCHEMA = "openstitch.ia-data.candidate-set/1"
MANIFEST_SCHEMA = "openstitch.ia-data.manifest/1"
FAMILIES = ("ellipse", "rect", "band", "star", "blob", "l_shape", "u_shape")
HOLDOUT_PERCENT = 20
RIGHTS = {"status": "cleared", "basis": "geometry generated by this script; no third-party asset"}

# Candidate catalogue. Technique names follow scripts/auto_digitize_ranker.py.
# "$axis" is replaced by the principal-axis angle of the shape (degrees).
CANDIDATES = (
    ("tatami_a0", "tatami", [{"op": "set_params", "params": {"angle_deg": 0.0}}]),
    ("tatami_a45", "tatami", [{"op": "set_params", "params": {"angle_deg": 45.0}}]),
    ("tatami_a90", "tatami", [{"op": "set_params", "params": {"angle_deg": 90.0}}]),
    ("tatami_axis", "tatami", [{"op": "set_params", "params": {"angle_deg": "$axis"}}]),
    ("running", "running", [{"op": "set_stitch_type", "type": "running"}]),
    ("directional", "directional", [{"op": "directional_guides"}]),
    ("spiral", "spiral", [{"op": "set_stitch_type", "type": "spiral_fill"}]),
    ("contour", "contour", [{"op": "set_stitch_type", "type": "contour_fill"}]),
    ("auto_satin", "auto_satin", [{"op": "auto_satin"}]),
)
CANDIDATE_IDS = tuple(c[0] for c in CANDIDATES)
# empty = the engine accepted the plan but sewed no visible stitch (a real negative).
STATUSES = ("measured", "refused", "empty", "failed")
METRIC_KEYS = (
    "covered_ratio", "overflow_ratio", "coverage_measured", "stitches", "jumps",
    "trims", "color_changes", "thread_m", "short_stitches", "long_moves_without_trim",
    "travel_mm", "quality_errors", "quality_warnings", "layers_mean", "layers_p99",
    "layers_max", "area_over_2_layers_mm2", "area_over_3_layers_mm2",
    "area_over_4_layers_mm2",
)


def fail(message: str) -> None:
    raise ValueError(message)


def canonical(obj: object) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --- geometry ---------------------------------------------------------------

def r2(v: float) -> float:
    # 0.01 mm grid: absorbs last-ulp libm differences between platforms.
    return round(v, 2) + 0.0


def area(points: list) -> float:
    s = 0.0
    for i, (x0, y0) in enumerate(points):
        x1, y1 = points[(i + 1) % len(points)]
        s += x0 * y1 - x1 * y0
    return s / 2.0


def perimeter(points: list) -> float:
    return sum(math.dist(points[i], points[(i + 1) % len(points)]) for i in range(len(points)))


def convex_hull(points: list) -> list:
    pts = sorted(set(map(tuple, points)))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower, upper = [], []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]


def principal_axis_deg(points: list) -> float:
    n = len(points)
    cx = sum(p[0] for p in points) / n
    cy = sum(p[1] for p in points) / n
    sxx = sum((p[0] - cx) ** 2 for p in points)
    syy = sum((p[1] - cy) ** 2 for p in points)
    sxy = sum((p[0] - cx) * (p[1] - cy) for p in points)
    deg = math.degrees(0.5 * math.atan2(2.0 * sxy, sxx - syy))
    return round(deg % 180.0, 1) + 0.0


def transform(points: list, rot_deg: float, scale: float = 1.0) -> list:
    c, s = math.cos(math.radians(rot_deg)), math.sin(math.radians(rot_deg))
    out = []
    for x, y in points:
        p = [r2((x * c - y * s) * scale), r2((x * s + y * c) * scale)]
        if not out or p != out[-1]:
            out.append(p)
    if len(out) > 1 and out[0] == out[-1]:
        out.pop()
    if area(out) < 0:
        out.reverse()
    return out


def radial(radii: list) -> list:
    n = len(radii)
    return [[r * math.cos(2 * math.pi * i / n), r * math.sin(2 * math.pi * i / n)]
            for i, r in enumerate(radii)]


def make_shape(family: str, rng: random.Random) -> tuple:
    """Returns (raw points, generator params). Every polygon is simple by construction."""
    if family == "ellipse":
        w, h = rng.uniform(6, 60), rng.uniform(4, 40)
        pts = [[w / 2 * math.cos(2 * math.pi * i / 64), h / 2 * math.sin(2 * math.pi * i / 64)]
               for i in range(64)]
        return pts, {"width_mm": round(w, 2), "height_mm": round(h, 2)}
    if family == "rect":
        w, h = rng.uniform(5, 60), rng.uniform(5, 40)
        return [[-w / 2, -h / 2], [w / 2, -h / 2], [w / 2, h / 2], [-w / 2, h / 2]], \
            {"width_mm": round(w, 2), "height_mm": round(h, 2)}
    if family == "band":
        length, width = rng.uniform(15, 70), rng.uniform(0.8, 7.0)
        return [[-length / 2, -width / 2], [length / 2, -width / 2],
                [length / 2, width / 2], [-length / 2, width / 2]], \
            {"length_mm": round(length, 2), "width_mm": round(width, 2)}
    if family == "star":
        n = rng.randint(4, 9)
        ro = rng.uniform(8, 30)
        ri = ro * rng.uniform(0.25, 0.7)
        return radial([ro if i % 2 == 0 else ri for i in range(2 * n)]), \
            {"branches": n, "outer_mm": round(ro, 2), "inner_mm": round(ri, 2)}
    if family == "blob":
        base = rng.uniform(6, 28)
        harmonics = [(k, rng.uniform(0, 0.18), rng.uniform(0, 2 * math.pi)) for k in (2, 3, 5)]
        radii = [base * (1 + sum(a * math.cos(k * 2 * math.pi * i / 72 + ph)
                                 for k, a, ph in harmonics)) for i in range(72)]
        return radial(radii), {"base_mm": round(base, 2)}
    if family == "l_shape":
        w, h, t = rng.uniform(15, 50), rng.uniform(15, 50), rng.uniform(2, 10)
        t = min(t, w * 0.6, h * 0.6)
        return [[0, 0], [w, 0], [w, t], [t, t], [t, h], [0, h]], \
            {"width_mm": round(w, 2), "height_mm": round(h, 2), "thickness_mm": round(t, 2)}
    if family == "u_shape":
        w, h, t = rng.uniform(15, 50), rng.uniform(12, 45), rng.uniform(2, 8)
        t = min(t, w * 0.3, h * 0.6)
        return [[0, 0], [w, 0], [w, h], [w - t, h], [w - t, t], [t, t], [t, h], [0, h]], \
            {"width_mm": round(w, 2), "height_mm": round(h, 2), "thickness_mm": round(t, 2)}
    fail("unknown family: " + family)


def generate_shape(seed: int, index: int) -> dict:
    # One independent RNG per shape: shape i does not depend on the count asked.
    rng = random.Random(f"{GENERATOR}:{seed}:{index}")
    family = FAMILIES[rng.randrange(len(FAMILIES))]
    raw, params = make_shape(family, rng)
    tiny = rng.random() < 0.08
    scale = 1.0
    if tiny:
        extent = max(max(p[0] for p in raw) - min(p[0] for p in raw),
                     max(p[1] for p in raw) - min(p[1] for p in raw))
        scale = rng.uniform(1.5, 4.0) / extent
    rot = round(rng.uniform(0, 180), 1)
    # Center on the bounding box so the shape sits in the hoop.
    cx = (max(p[0] for p in raw) + min(p[0] for p in raw)) / 2
    cy = (max(p[1] for p in raw) + min(p[1] for p in raw)) / 2
    pts = transform([[x - cx, y - cy] for x, y in raw], rot, scale)
    a, per = area(pts), perimeter(pts)
    hull = convex_hull(pts)
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    w, h = max(xs) - min(xs), max(ys) - min(ys)
    flags = []
    if tiny:
        flags.append("tiny")
    if family == "band" and params["width_mm"] * scale < 2.0:
        flags.append("thin")
    convexity = a / area(hull) if len(hull) >= 3 and area(hull) > 0 else 1.0
    if convexity < 0.6:
        flags.append("very_concave")
    geometry = {
        "area_mm2": round(a, 3),
        "perimeter_mm": round(per, 3),
        "compactness": round(4 * math.pi * a / (per * per), 4) if per > 0 else 0.0,
        "convexity": round(convexity, 4),
        "bbox_mm": [round(w, 2), round(h, 2)],
        "principal_axis_deg": principal_axis_deg(pts),
        "vertices": len(pts),
    }
    body = {"family": family, "points_mm": pts}
    shape_id = sha256_bytes(canonical(body).encode())[:16]
    return {
        "schema": SHAPE_SCHEMA,
        "shape_id": shape_id,
        "split_group": shape_id,
        "source": {"kind": "synthetic", "generator": GENERATOR, "seed": seed, "index": index},
        "rights": RIGHTS,
        "family": family,
        "params": params,
        "rotation_deg": rot,
        "scale": round(scale, 4),
        "flags": flags,
        "geometry": geometry,
        "points_mm": pts,
    }


def split_of(group: str) -> str:
    bucket = int(sha256_bytes(("split:" + group).encode())[:8], 16) % 100
    return "holdout" if bucket < HOLDOUT_PERCENT else "train"


# --- engine measurement -----------------------------------------------------

def candidate_ops(shape: dict, ops: list) -> list:
    out = []
    for op in ops:
        op = json.loads(json.dumps(op))
        op["object"] = "$s"
        params = op.get("params")
        if params and params.get("angle_deg") == "$axis":
            params["angle_deg"] = shape["geometry"]["principal_axis_deg"]
        out.append(op)
    return out


def batch_for(shape: dict, ops: list) -> dict:
    return {"schema": "openstitch.batch/1", "operations": [
        {"op": "add_shape", "as": "s", "shape": "polygon", "points_mm": shape["points_mm"]},
        {"op": "set_color", "object": "$s", "rgb": "#1E64C8"},
    ] + candidate_ops(shape, ops)}


def metrics_from(check: dict, density: dict) -> dict:
    """Maps engine reports to the flat metric dict. Missing engine fields are errors."""
    seq = check["sequence"]
    objects = check["objects"]
    if len(objects) != 1:
        fail("expected exactly one object in the quality report")
    obj = objects[0]
    over = density["area_over_mm2"]
    measured = bool(obj["measured"])
    return {
        "covered_ratio": obj["covered_ratio"] if measured else None,
        "overflow_ratio": obj["overflow_ratio"] if measured else None,
        "coverage_measured": measured,
        "stitches": seq["stitches"],
        "jumps": seq["jumps"],
        "trims": seq["trims"],
        "color_changes": seq["color_changes"],
        "thread_m": seq["thread_m"],
        "short_stitches": seq["short_stitches"],
        "long_moves_without_trim": seq["long_moves_without_trim"],
        "travel_mm": round(seq["moves_between"]["travel_mm"] + seq["moves_within"]["travel_mm"], 3),
        "quality_errors": check["summary"]["errors"],
        "quality_warnings": check["summary"]["warnings"],
        "layers_mean": density["layers_mean"],
        "layers_p99": density["layers_p99"],
        "layers_max": density["layers_max"],
        "area_over_2_layers_mm2": over["2_layers"],
        "area_over_3_layers_mm2": over["3_layers"],
        "area_over_4_layers_mm2": over["4_layers"],
    }


class CliEngine:
    """Runs openstitch-cli. `run(args) -> (returncode, stdout)` is the only seam tests replace."""

    def __init__(self, cli: str, workdir: Path):
        self.cli = cli
        self.workdir = workdir
        self.template = workdir / "template.osp"
        rc, out = self.run(["project", "new", str(self.template), "--width-mm", "200",
                            "--height-mm", "200"])
        if rc != 0:
            fail("openstitch-cli project new failed: " + out[-400:])

    def run(self, args: list) -> tuple:
        p = subprocess.run([self.cli] + args, capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        return p.returncode, p.stdout

    def version(self) -> str:
        rc, out = self.run(["--version"])
        return out.strip().splitlines()[0] if rc == 0 and out.strip() else "unknown"

    def measure(self, shape: dict, cid: str, technique: str, ops: list) -> dict:
        record = {"id": cid, "technique": technique, "ops": candidate_ops(shape, ops),
                  "status": "failed", "error": None, "metrics": None}
        with tempfile.TemporaryDirectory(dir=self.workdir) as tmp:
            batch, osp = Path(tmp) / "b.json", Path(tmp) / "c.osp"
            batch.write_text(canonical(batch_for(shape, ops)), encoding="utf-8")
            rc, out = self.run(["project", "apply", str(self.template), str(batch),
                                "-o", str(osp), "--json"])
            try:
                report = json.loads(out)
            except json.JSONDecodeError:
                record["error"] = {"code": "E_BAD_JSON", "stage": "apply", "rc": rc}
                return record
            if not report.get("ok"):
                bad = next((o for o in report.get("outcomes", []) if not o.get("ok")), None)
                err = (bad or {}).get("error") or report.get("error") or {}
                record["status"] = "refused"
                record["error"] = {"code": err.get("code", "E_UNKNOWN"), "stage": "apply",
                                   "op": (bad or {}).get("op")}
                return record
            outputs = {}
            for name in ("check", "density"):
                rc, out = self.run(["project", name, str(osp), "--json"])
                try:
                    outputs[name] = json.loads(out)
                except json.JSONDecodeError:
                    record["error"] = {"code": "E_BAD_JSON", "stage": name, "rc": rc}
                    return record
                if outputs[name].get("schema") == "openstitch.error/1":
                    err = outputs[name].get("error") or {}
                    record["status"] = "empty" if name == "density" else "failed"
                    record["error"] = {"code": err.get("code", "E_UNKNOWN"), "stage": name}
                    return record
            try:
                record["metrics"] = metrics_from(outputs["check"], outputs["density"])
            except (KeyError, TypeError, ValueError) as exc:
                record["error"] = {"code": "E_REPORT_SHAPE", "stage": "metrics",
                                   "detail": str(exc)[:200]}
                return record
            record["status"] = "measured"
            return record


def candidate_set(engine, shape: dict, engine_info: dict) -> dict:
    return {
        "schema": SET_SCHEMA,
        "sample_id": shape["shape_id"],
        "split_group": shape["split_group"],
        "split": split_of(shape["split_group"]),
        "source": shape["source"],
        "rights": shape["rights"],
        "family": shape["family"],
        "flags": shape["flags"],
        "geometry": shape["geometry"],
        "engine": engine_info,
        "candidates": [engine.measure(shape, cid, tech, ops) for cid, tech, ops in CANDIDATES],
        "label": None,
    }


# --- validation -------------------------------------------------------------

def check_shape(row: dict) -> None:
    if not isinstance(row, dict) or row.get("schema") != SHAPE_SCHEMA:
        fail("shape: wrong schema")
    if row.get("family") not in FAMILIES:
        fail("shape: unknown family")
    pts = row.get("points_mm")
    if not isinstance(pts, list) or len(pts) < 3:
        fail("shape: points_mm needs >= 3 vertices")
    for p in pts:
        if not (isinstance(p, list) and len(p) == 2 and all(
                type(v) in (int, float) and math.isfinite(v) and abs(v) <= 1000 for v in p)):
            fail("shape: bad vertex")
    if area(pts) <= 0:
        fail("shape: polygon must be counter-clockwise with positive area")
    expected = sha256_bytes(canonical({"family": row["family"], "points_mm": pts}).encode())[:16]
    if row.get("shape_id") != expected:
        fail("shape: shape_id does not match geometry")
    if row.get("rights", {}).get("status") != "cleared":
        fail("shape: only rights-cleared shapes may enter the corpus")


def check_set(row: dict) -> None:
    if not isinstance(row, dict) or row.get("schema") != SET_SCHEMA:
        fail("set: wrong schema")
    if row.get("label") is not None:
        fail("set: L1 corpus carries no label")
    if row.get("split") != split_of(row.get("split_group", "")):
        fail("set: split does not match split_group hash")
    if row.get("rights", {}).get("status") != "cleared":
        fail("set: rights not cleared")
    ids = [c.get("id") for c in row.get("candidates", [])]
    if ids != list(CANDIDATE_IDS):
        fail("set: candidates must follow the catalogue order")
    for c in row["candidates"]:
        if c.get("status") not in STATUSES:
            fail("set: bad candidate status")
        m = c.get("metrics")
        if c["status"] == "measured":
            if not isinstance(m, dict) or set(m) != set(METRIC_KEYS):
                fail("set: measured candidate needs exactly the metric keys")
            for k, v in m.items():
                if v is None and k in ("covered_ratio", "overflow_ratio") and not m["coverage_measured"]:
                    continue
                if isinstance(v, bool):
                    continue
                if type(v) not in (int, float) or not math.isfinite(v) or v < 0:
                    fail("set: metric must be finite and >= 0: " + k)
        elif m is not None or not c.get("error"):
            fail("set: refused/failed candidate needs an error and no metrics")


def read_jsonl(path: Path) -> list:
    rows = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as exc:
                fail(f"{path.name}:{n}: {exc}")
    return rows


def write_jsonl(path: Path, rows: list) -> dict:
    data = "".join(canonical(r) + "\n" for r in rows).encode("utf-8")
    path.write_bytes(data)
    return {"sha256": sha256_bytes(data), "bytes": len(data), "rows": len(rows)}


def validate_dir(out: Path) -> dict:
    manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("schema") != MANIFEST_SCHEMA:
        fail("manifest: wrong schema")
    for name, info in manifest["files"].items():
        data = (out / name).read_bytes()
        if sha256_bytes(data) != info["sha256"]:
            fail("manifest: checksum mismatch for " + name)
    shapes = read_jsonl(out / "shapes.jsonl")
    for row in shapes:
        check_shape(row)
    sets = read_jsonl(out / "candidates.jsonl") if (out / "candidates.jsonl").exists() else []
    for row in sets:
        check_set(row)
    if sets and [s["sample_id"] for s in sets] != [s["shape_id"] for s in shapes]:
        fail("candidates.jsonl does not follow shapes.jsonl")
    return {"shapes": len(shapes), "candidate_sets": len(sets)}


# --- commands ---------------------------------------------------------------

def coverage(shapes: list, sets: list) -> dict:
    fam = {f: 0 for f in FAMILIES}
    flags = {}
    for s in shapes:
        fam[s["family"]] += 1
        for f in s["flags"]:
            flags[f] = flags.get(f, 0) + 1
    split = {"train": 0, "holdout": 0}
    for s in shapes:
        split[split_of(s["split_group"])] += 1
    status = {cid: {st: 0 for st in STATUSES} for cid in CANDIDATE_IDS}
    for row in sets:
        for c in row["candidates"]:
            status[c["id"]][c["status"]] += 1
    return {"families": fam, "flags": dict(sorted(flags.items())), "split": split,
            "candidate_status": status if sets else None}


def generate(seed: int, count: int) -> list:
    if count < 1 or count > 100000:
        fail("count must be in [1 ; 100000]")
    return [generate_shape(seed, i) for i in range(count)]


def build(out: Path, seed: int, count: int, engine=None, engine_info=None, jobs: int = 1) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    for name in ("shapes.jsonl", "candidates.jsonl", "manifest.json"):
        if (out / name).exists():
            fail(f"{out / name} exists: refusing to overwrite a corpus")
    shapes = generate(seed, count)
    files = {"shapes.jsonl": write_jsonl(out / "shapes.jsonl", shapes)}
    sets = []
    if engine is not None:
        with ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
            # map() keeps input order: output is independent of scheduling.
            sets = list(pool.map(lambda s: candidate_set(engine, s, engine_info), shapes))
        files["candidates.jsonl"] = write_jsonl(out / "candidates.jsonl", sets)
    manifest = {
        "schema": MANIFEST_SCHEMA,
        "generator": GENERATOR,
        "seed": seed,
        "count": count,
        "holdout_percent": HOLDOUT_PERCENT,
        "candidate_catalogue": [{"id": c, "technique": t} for c, t, _ in CANDIDATES],
        "engine": engine_info,
        "rights": RIGHTS,
        "files": files,
        "coverage": coverage(shapes, sets),
    }
    (out / "manifest.json").write_bytes(
        (json.dumps(manifest, sort_keys=True, indent=2, ensure_ascii=True) + "\n").encode())
    return manifest


def find_cli(explicit: str | None) -> str:
    if explicit:
        return explicit
    if os.environ.get("OPENSTITCH_CLI"):
        return os.environ["OPENSTITCH_CLI"]
    fail("openstitch-cli not given: use --cli PATH or OPENSTITCH_CLI")


def main(argv: list | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate", help="shapes only, no engine")
    g.add_argument("out", type=Path)
    g.add_argument("--seed", type=int, default=42)
    g.add_argument("--count", type=int, default=100)
    b = sub.add_parser("build", help="shapes + candidates measured by openstitch-cli")
    b.add_argument("out", type=Path)
    b.add_argument("--seed", type=int, default=42)
    b.add_argument("--count", type=int, default=100)
    b.add_argument("--cli")
    b.add_argument("--engine-rev", default="unknown", help="git SHA of the engine build")
    b.add_argument("--jobs", type=int, default=4)
    v = sub.add_parser("validate")
    v.add_argument("out", type=Path)
    args = ap.parse_args(argv)
    try:
        if args.cmd == "generate":
            m = build(args.out, args.seed, args.count)
        elif args.cmd == "build":
            cli = find_cli(args.cli)
            with tempfile.TemporaryDirectory(prefix="ia-data-") as work:
                engine = CliEngine(cli, Path(work))
                info = {"cli_version": engine.version(), "engine_rev": args.engine_rev}
                m = build(args.out, args.seed, args.count, engine, info, args.jobs)
        else:
            print(json.dumps(validate_dir(args.out), sort_keys=True))
            return 0
    except ValueError as exc:
        print("error: " + str(exc), file=sys.stderr)
        return 1
    print(json.dumps(m["coverage"], sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
